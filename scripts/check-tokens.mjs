import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const read = (p) => readFileSync(new URL(p, import.meta.url), 'utf8');
const exported = read('../src/design-tokens/figma-tokens.css');
const bridge = read('../src/design-tokens/legacy-utility-bridge.css');
const imports = read('../src/index.css');
const preview = read('../.storybook/preview.ts');
const count = (text) => [...text.matchAll(/^\s*--[\w-]+:/gm)].length;
assert.ok(count(exported) >= 350, 'Missing exported Figma tokens');
assert.match(exported, /--color-valle-600:\s*#1c7c54;/i);
assert.match(exported, /--color-blue-600:\s*#2563eb;/i);
assert.match(exported, /--color-theme-background-primary:\s*var\(--color-valle-600\)/);
assert.match(exported, /--typography-family-font-family-font:\s*var\(--typography-family-font-poppins\)/);
assert.match(imports, /figma-tokens\.css/);
assert.doesNotMatch(imports, /avila-theme\.css|primitive\.css/);
assert.match(preview, /initialGlobals: \{ theme: 'avila' \}/);
assert.doesNotMatch(bridge, /#[0-9a-f]{3,8}\b/i);
const canonical = new Set([...exported.matchAll(/^\s*(--[\w-]+):/gm)].map(m => m[1]));
const refs = [...bridge.matchAll(/var\((--[\w-]+)\)/g)].map(m => m[1]);
for (const token of refs) assert.ok(canonical.has(token), `Undeclared canonical token: ${token}`);
console.log(`Valid Figma export (${count(exported)} declarations), ${refs.length} mapped legacy references, two theme modes`);
